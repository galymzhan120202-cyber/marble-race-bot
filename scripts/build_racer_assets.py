"""Rebuild the browser portraits from the same artist code as video sprites."""
import sys
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root))
from race_sim import RACER_POOL
from racer_art import IDENTITIES, make_portrait

output = root / 'assets' / 'racers'
output.mkdir(parents=True, exist_ok=True)
for racer in RACER_POOL:
    make_portrait(racer['color'], 256, name=racer['name']).save(output / (racer['name'].lower()+'.png'))
catalog = json.dumps(IDENTITIES, ensure_ascii=False, indent=2) + '\n'
(output / 'manifest.json').write_text(catalog, encoding='utf-8')
(output / 'catalog.js').write_text('// Generated by scripts/build_racer_assets.py; edit racer_art.py.\n'
                                 + 'const RACER_IDENTITIES = ' + catalog.rstrip() + ';\n', encoding='utf-8')
print(f'Built {len(RACER_POOL)} portraits in {output}')
